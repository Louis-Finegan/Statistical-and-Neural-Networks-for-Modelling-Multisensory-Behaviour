"""Reproduce figures from MAP_ANN-v3.ipynb."""
from src.common import np, plt, torch, F, Trainer, configure, save_figure, save_checkpoint
from src import networks as ANN, mle as MLE, map as MAP, plotting as pw
from src.simulation import PerceivedUniSensoryData, UniSensorySimulation1, map_reference, evaluate_map

def main():
    options = configure('chapter7')
    # Five stimulus pairs used in the original training set (audio, visual).
    training_locations = [(0, 0), (-5, 5), (-10, 8), (2, 7), (-5, -10)]
    audio_samples, visual_samples = [], []
    for audio_location, visual_location in training_locations:
        audio_samples.append(PerceivedUniSensoryData(audio_location, 8, 2000))
        visual_samples.append(PerceivedUniSensoryData(visual_location, 2.5, 2000))
    Audio_Stimuli = np.concatenate(audio_samples)
    Visual_Stimuli = np.concatenate(visual_samples)
    model_Std_unity, model_Std_nonunity, model_means_unity, model_means_nonunity, model_prop = map_reference()
    model_prop_ = np.array(model_prop)
    mean_prop = np.mean(model_prop_)
    sources = np.arange(-25, 26, step=5)
    print(mean_prop)
    print(np.mean(model_prop_ * (1 / (30 * np.sqrt(2 * np.pi)) * np.exp(-0.5 * (sources / 30) ** 2) + 1 / 180)))
    mask = np.abs(Visual_Stimuli - Audio_Stimuli) < 8
    w_audio = 2.5 ** 2 / (2.5 ** 2 + 8 ** 2)
    w_visual = 8 ** 2 / (2.5 ** 2 + 8 ** 2)
    MLE = w_audio * Audio_Stimuli + w_visual * Visual_Stimuli
    model_unity = mean_prop * MLE + (1 - mean_prop) * Audio_Stimuli
    model_nonunity = Audio_Stimuli
    prob = np.abs(Visual_Stimuli - Audio_Stimuli) < 8
    print(f'{len(prob[prob == False]) / len(prob) * 100}% of the trials are non-unity')
    X_train = torch.tensor(np.column_stack((Visual_Stimuli, Audio_Stimuli)), dtype=torch.float32)
    Y_train = torch.tensor(np.column_stack((model_unity, model_nonunity, prob)), dtype=torch.float32)
    MAP_NN1 = ANN.ANN_MAP3()
    optimizer = torch.optim.AdamW(MAP_NN1.parameters(), lr=0.0001, weight_decay=1e-05)
    epochs = options.map_epochs
    loss_history = {'total': [], 'mean': [], 'probability': []}
    for epoch in range(epochs):
        outputs = MAP_NN1(X_train)
        mean_loss = F.mse_loss(outputs[:, :2], Y_train[:, :2])
        prob_loss = F.binary_cross_entropy(outputs[:, 2], Y_train[:, 2])
        total_loss = mean_loss + prob_loss
        optimizer.zero_grad()
        total_loss.backward()
        optimizer.step()
        loss_history['total'].append(total_loss.item())
        loss_history['mean'].append(mean_loss.item())
        loss_history['probability'].append(prob_loss.item())
        if (epoch + 1) % 100 == 0:
            print(f'Epoch [{epoch + 1}/{epochs}] Total: {total_loss.item():.4f} Mean: {mean_loss.item():.4f} Prob: {prob_loss.item():.4f}')
    save_checkpoint(MAP_NN1, 'chapter7_ANN.pth')
    plt.figure(figsize=(10, 5))
    plt.title('Total Loss Over Epochs', loc='left')
    plt.plot(loss_history['total'], linewidth=3, color='black')
    plt.xlabel('Epochs')
    plt.ylabel('Loss')
    plt.grid(True)
    save_figure()
    plt.figure(figsize=(10, 5))
    plt.title('Linear mean Loss Over Epochs', loc='left')
    plt.plot(loss_history['mean'], linewidth=3, color='black')
    plt.xlabel('Epochs')
    plt.ylabel('Loss')
    plt.grid(True)
    save_figure()
    plt.figure(figsize=(10, 5))
    plt.title('Sigmoid Loss Over Epochs', loc='left')
    plt.plot(loss_history['probability'], linewidth=3, color='black')
    plt.xlabel('Epochs')
    plt.ylabel('Loss')
    plt.grid(True)
    save_figure()
    X_test_1 = torch.tensor(np.column_stack((0, 0)), dtype=torch.float32)
    print(X_test_1)
    MAP_NN1.eval()
    Y_test_1 = MAP_NN1(X_test_1)
    print(Y_test_1)
    audio_loc = 0
    visual_loc = 10
    Audio_Stimuli = PerceivedUniSensoryData(audio_loc, sd=8, NTrials=2000)
    Visual_Stimuli = PerceivedUniSensoryData(visual_loc, sd=2.5, NTrials=2000)
    MLE = w_audio * Audio_Stimuli + w_visual * Visual_Stimuli
    model_unity = mean_prop * MLE + (1 - mean_prop) * Audio_Stimuli
    model_nonunity = Audio_Stimuli
    X_test = torch.tensor(np.column_stack((Visual_Stimuli, Audio_Stimuli)), dtype=torch.float32)
    MAP_NN1.eval()
    Y_test = MAP_NN1(X_test)
    plt.figure(figsize=(10, 6))
    plt.title('Audiovisual Visual Integration (Unity)', loc='left')
    plt.hist(X_test.detach().numpy()[:, 0], bins=50, alpha=0.1, label='Visual Stimuli', density=True, color='blue')
    plt.hist(X_test.detach().numpy()[:, 1], bins=50, alpha=0.1, label='Audio Stimuli', density=True, color='orange')
    plt.hist(model_unity, bins=50, alpha=0.3, label='Model Unity', density=True, color='red')
    plt.hist(Y_test.detach().numpy()[:, 0], bins=50, alpha=0.5, label='ANN Unity', density=True, color='green')
    plt.axvline(x=Y_test.detach().numpy()[:, 0].mean(), color='green', linestyle='--')
    plt.axvline(x=model_unity.mean(), color='red', linestyle='--')
    plt.xlabel('Stimuli Localisation (degrees)')
    plt.ylabel('Density')
    plt.text(-20, 0.16, f'$\\left|\\hat y_{{AV}}^{{model}} - \\hat{{y}}_{{AV}}^{{ANN}}\\right| = {np.abs(model_unity.mean() - Y_test.detach().numpy()[:, 0].mean()):.3f}$', fontsize=12, color='black')
    plt.legend()
    save_figure()
    plt.figure(figsize=(10, 6))
    plt.title('Audiovisual Visual Integration (Non-Unity)', loc='left')
    plt.hist(X_test.detach().numpy()[:, 0], bins=50, alpha=0.1, label='Visual Stimuli', density=True, color='blue')
    plt.hist(X_test.detach().numpy()[:, 1], bins=50, alpha=0.1, label='Audio Stimuli', density=True, color='orange')
    plt.hist(model_nonunity, bins=50, alpha=0.3, label='Model Non-Unity', density=True, color='red')
    plt.hist(Y_test.detach().numpy()[:, 1], bins=50, alpha=0.5, label='ANN Non-Unity', density=True, color='green')
    plt.axvline(x=Y_test.detach().numpy()[:, 1].mean(), color='green', linestyle='--')
    plt.axvline(x=model_nonunity.mean(), color='red', linestyle='--')
    plt.xlabel('Stimuli Localisation (degrees)')
    plt.ylabel('Density')
    plt.text(-20, 0.12, f'$\\left|\\hat y_{{AV}}^{{model}} - \\hat{{y}}_{{AV}}^{{ANN}}\\right| = {np.abs(model_nonunity.mean() - Y_test.detach().numpy()[:, 1].mean()):.3f}$', fontsize=12, color='black')
    plt.legend()
    save_figure()
    sources = np.arange(-25, 26, step=5)
    audio_loc = np.array([0])
    Visual_stimuli_many = UniSensorySimulation1(sources, 2.5, 2000)
    Audio_stimuli_many = UniSensorySimulation1(audio_loc, 8, 2000)
    stimuli_means_nn1_unity, stimuli_stds_nn1_unity, stimuli_means_nn1_nonunity, stimuli_stds_nn1_nonunity, stimuli_prop_nn1 = evaluate_map(Visual_stimuli_many, Audio_stimuli_many, sources, MAP_NN1)
    plt.figure(figsize=(10, 5))
    plt.plot(sources, stimuli_means_nn1_unity, marker='o', linestyle='-', label='Mean Unity')
    plt.plot(sources, stimuli_means_nn1_nonunity, marker='o', linestyle='-', label='Mean Non-Unity')
    plt.plot(sources, model_means_unity, marker='x', alpha=0.5, linestyle='--', label='Model Mean Unity')
    plt.plot(sources, model_means_nonunity, marker='x', alpha=0.5, linestyle='--', label='Model Mean Non-Unity')
    plt.xlabel('Spatial Disparity (degrees)')
    plt.ylabel('Bias')
    plt.ylim(-1.5, 2)
    plt.legend()
    plt.tight_layout()
    save_figure()
    plt.figure(figsize=(10, 5))
    plt.plot(sources, stimuli_stds_nn1_unity, marker='o', linestyle='-', label='ANN Standard Deviation Unity')
    plt.plot(sources, stimuli_stds_nn1_nonunity, marker='o', linestyle='-', label='ANN Standard Deviation Non-Unity')
    plt.plot(sources, model_Std_unity, marker='x', alpha=0.5, linestyle='--', label='Model Standard Deviation Unity')
    plt.plot(sources, model_Std_nonunity, marker='x', alpha=0.5, linestyle='--', label='Model Standard Deviation Non-Unity')
    plt.xlabel('Spatial Disparity (degrees)')
    plt.ylabel('Standard Deviation of the Audiovisual Integration')
    plt.legend()
    plt.ylim(0, 18)
    plt.tight_layout()
    save_figure()
    plt.figure(figsize=(10, 5))
    plt.plot(sources, stimuli_prop_nn1, marker='o', linestyle='-', label='ANN Probability of Unity')
    plt.plot(sources, model_prop_, marker='x', alpha=0.5, linestyle='--', label='Model Probability of Unity')
    plt.ylabel('Probability of Unity')
    plt.xlabel('Spatial Disparity (degrees)')
    plt.ylim(0, 1.1)
    plt.legend()
    plt.tight_layout()
    save_figure()

if __name__ == "__main__":
    main()
