"""Reproduce figures from MLE-ANN-v4.ipynb."""
from src.common import np, plt, torch, nn, Trainer, configure, save_figure, save_checkpoint
from src import networks as ANN, mle as MLE, map as MAP, plotting as pw
from src.simulation import PerceivedUniSensoryData, UniSensorySimulation1, mle_reference, evaluate_ann, jumble_data

def main():
    options = configure('chapter5')
    def make_trainer(model, criterion, optimizer):
        return Trainer(model, criterion, optimizer, epochs=options.epochs)
    Neural_Net1_unjumbled = ANN.ANN1()
    Neural_Net2_unjumbled = ANN.ANN2()
    Neural_Net1_jumbled = ANN.ANN1()
    Neural_Net2_jumbled = ANN.ANN2()
    visual_mean = 0
    audio_mean = 0
    Visual_stimuli = PerceivedUniSensoryData(visual_mean, 2.5, 2000)
    Audio_stimuli = PerceivedUniSensoryData(audio_mean, 8, 2000)
    Model = MLE.ModelMLE(Audio_stimuli, Visual_stimuli)
    X_unjumbled = torch.tensor(np.column_stack((Visual_stimuli, Audio_stimuli)), dtype=torch.float32)
    Y_unjumbled = torch.tensor(Model.model(), dtype=torch.float32)
    Visual_sources = np.random.uniform(-5, 5, 1000)
    Audio_sources = np.random.uniform(-5, 5, 1000)
    Visual_stimuli_many = UniSensorySimulation1(Visual_sources, 2.5, 2000)
    Audio_stimuli_many = UniSensorySimulation1(Audio_sources, 8, 2000)
    jumbled_visual_stimuli = jumble_data(Visual_stimuli_many)
    jumbled_audio_stimuli = jumble_data(Audio_stimuli_many)
    plt.figure()
    plt.hist(jumbled_visual_stimuli, bins=50, alpha=0.5, label='Visual Stimuli', color='coral')
    plt.xlabel('Jumbled Visual Stimuli')
    plt.ylabel('Frequency')
    plt.title('Histogram of Jumbled Visual Stimuli')
    save_figure()
    plt.figure()
    plt.hist(jumbled_audio_stimuli, bins=50, alpha=0.5, label='Audio Stimuli', color='lightcoral')
    plt.xlabel('Jumbled Audio Stimuli')
    plt.ylabel('Frequency')
    plt.title('Histogram of Jumbled Audio Stimuli')
    save_figure()
    Model_jumbled = MLE.ModelMLE(jumbled_audio_stimuli, jumbled_visual_stimuli)
    X_jumbled = torch.tensor(np.column_stack((jumbled_visual_stimuli, jumbled_audio_stimuli)), dtype=torch.float32)
    Y_jumbled = torch.tensor(Model_jumbled.model(), dtype=torch.float32)
    criterion = nn.MSELoss()
    optimizer1_unjumbled = torch.optim.SGD(Neural_Net1_unjumbled.parameters(), lr=0.01)
    optimizer2_unjumbled = torch.optim.SGD(Neural_Net2_unjumbled.parameters(), lr=0.01)
    optimizer1_jumbled = torch.optim.SGD(Neural_Net1_jumbled.parameters(), lr=0.01)
    optimizer2_jumbled = torch.optim.SGD(Neural_Net2_jumbled.parameters(), lr=0.01)
    trainer_nueral_net1_unjumbled = make_trainer(Neural_Net1_unjumbled, criterion, optimizer1_unjumbled)
    trainer_nueral_net2_unjumbled = make_trainer(Neural_Net2_unjumbled, criterion, optimizer2_unjumbled)
    trainer_nueral_net1_jumbled = make_trainer(Neural_Net1_jumbled, criterion, optimizer1_jumbled)
    trainer_nueral_net2_jumbled = make_trainer(Neural_Net2_jumbled, criterion, optimizer2_jumbled)
    trainer_nueral_net1_unjumbled.train(X_unjumbled, Y_unjumbled)
    weights_nn1_unjumbled = trainer_nueral_net1_unjumbled.get_weights_history()
    loss_nn1_unjumbled = trainer_nueral_net1_unjumbled.get_loss_history()
    save_checkpoint(Neural_Net1_unjumbled, 'chapter5_ANN1_unjumbled.pth')
    save_checkpoint(Neural_Net2_unjumbled, 'chapter5_ANN2_unjumbled.pth')
    save_checkpoint(Neural_Net1_jumbled, 'chapter5_ANN1_jumbled.pth')
    save_checkpoint(Neural_Net2_jumbled, 'chapter5_ANN2_jumbled.pth')        
    plt.rcParams.update({'font.size': 15})
    pw.plot_weight_evolution(weights_nn1_unjumbled)
    plt.rcParams.update({'font.size': 15})
    plt.figure(figsize=(10, 5))
    plt.plot(loss_nn1_unjumbled, color='black', linewidth=3)
    plt.xlabel('Epochs')
    plt.ylabel('Loss')
    plt.title('Neural Network 1 Loss', loc='left')
    plt.grid(True)
    save_figure()
    trainer_nueral_net1_jumbled.train(X_jumbled, Y_jumbled)
    weights_nn1_jumbled = trainer_nueral_net1_jumbled.get_weights_history()
    loss_nn1_jumbled = trainer_nueral_net1_jumbled.get_loss_history()
    pw.plot_weight_evolution(weights_nn1_jumbled)
    plt.figure()
    plt.plot(loss_nn1_jumbled)
    plt.xlabel('Epoch')
    plt.ylabel('Loss')
    plt.title('Loss vs Epoch')
    save_figure()
    trainer_nueral_net2_unjumbled.train(X_unjumbled, Y_unjumbled)
    weights_nn2_unjumbled = trainer_nueral_net2_unjumbled.get_weights_history()
    loss_nn2_unjumbled = trainer_nueral_net2_unjumbled.get_loss_history()
    pw.plot_weight_evolution(weights_nn2_unjumbled)
    plt.figure(figsize=(10, 5))
    plt.plot(loss_nn2_unjumbled, color='black', linewidth=3)
    plt.xlabel('Epochs')
    plt.ylabel('Loss')
    plt.title('Neural Network 2 Loss', loc='left')
    plt.grid(True)
    save_figure()
    trainer_nueral_net2_jumbled.train(X_jumbled, Y_jumbled)
    weights_nn2_jumbled = trainer_nueral_net2_jumbled.get_weights_history()
    loss_nn2_jumbled = trainer_nueral_net2_jumbled.get_loss_history()
    pw.plot_weight_evolution(weights_nn2_jumbled)
    plt.figure()
    plt.plot(loss_nn2_jumbled)
    plt.xlabel('Epoch')
    plt.ylabel('Loss')
    plt.title('Loss vs Epoch')
    save_figure()
    hidden_weights_nn1_unjumbled = weights_nn1_unjumbled['hidden'][:, :, -1]
    output_weights_nn1_unjumbled = weights_nn1_unjumbled['output'][:, :, -1]
    print('Neural Network 1 (Unjumbled):')
    print('Hidden Layer Weights:', hidden_weights_nn1_unjumbled)
    print('Output Layer Weights:', output_weights_nn1_unjumbled)
    hidden_weights_nn2_unjumbled = weights_nn2_unjumbled['hidden'][:, :, -1]
    output_weights_nn2_unjumbled = weights_nn2_unjumbled['output'][:, :, -1]
    hidden_biases_nn2_unjumbled = Neural_Net2_unjumbled.hidden.bias.detach().numpy()
    output_biases_nn2_unjumbled = Neural_Net2_unjumbled.output.bias.detach().numpy()
    print('Neural Network 2 (Unjumbled):')
    print('Hidden Layer Weights:', hidden_weights_nn2_unjumbled)
    print('Hidden Layer Biases:', hidden_biases_nn2_unjumbled)
    print('Output Layer Weights:', output_weights_nn2_unjumbled)
    print('Output Layer Biases:', output_biases_nn2_unjumbled)
    visual_mean = -10
    audio_mean = 0
    Visual_stimuli = PerceivedUniSensoryData(visual_mean, 2.5, 2000)
    Audio_stimuli = PerceivedUniSensoryData(audio_mean, 8, 2000)
    Model = MLE.ModelMLE(Audio_stimuli, Visual_stimuli)
    integration = Model.model()
    ANN_integration_unjumbled = Neural_Net1_unjumbled(torch.tensor(np.column_stack((Visual_stimuli, Audio_stimuli)), dtype=torch.float32)).detach().numpy()
    ANN_integration_unjumbled1 = Neural_Net2_unjumbled(torch.tensor(np.column_stack((Visual_stimuli, Audio_stimuli)), dtype=torch.float32)).detach().numpy()
    print(np.abs(np.mean(integration) - np.mean(ANN_integration_unjumbled)))
    print(np.abs(np.mean(integration) - np.mean(ANN_integration_unjumbled1)))
    plt.figure(figsize=(10, 5))
    plt.title('Neural Network 1', loc='left')
    plt.hist(integration, label='MLE Model', color='red', alpha=0.5, bins=50, density=True)
    plt.hist(ANN_integration_unjumbled, label='Neural Network', color='green', alpha=0.5, bins=50, density=True)
    plt.axvline(x=np.mean(integration), color='red', linestyle='--')
    plt.axvline(x=np.mean(ANN_integration_unjumbled), color='green', linestyle='--')
    plt.xlabel('Stimuli Localisation (degrees)')
    plt.ylabel('Density')
    plt.text(-16.5, 0.175, f'$\\left|\\hat y_{{AV}}^{{model}} - \\hat{{y}}_{{AV}}^{{ANN}}\\right| = {np.abs(np.mean(integration) - np.mean(ANN_integration_unjumbled)):.3f}$', fontsize=12, color='black')
    plt.ylim(0, 0.2)
    plt.legend()
    save_figure()
    plt.figure(figsize=(10, 5))
    plt.title('Neural Network 2', loc='left')
    plt.hist(integration, label='MLE Model', color='red', alpha=0.5, bins=50, density=True)
    plt.hist(ANN_integration_unjumbled1, label='Neural Network', color='green', alpha=0.5, bins=50, density=True)
    plt.axvline(x=np.mean(integration), color='red', linestyle='--')
    plt.axvline(x=np.mean(ANN_integration_unjumbled1), color='green', linestyle='--')
    plt.xlabel('Stimuli Localisation (degrees)')
    plt.ylabel('Density')
    plt.text(-16.5, 0.175, f'$\\left|\\hat y_{{AV}}^{{model}} - \\hat{{y}}_{{AV}}^{{ANN}}\\right| = {np.abs(np.mean(integration) - np.mean(ANN_integration_unjumbled1)):.3f}$', fontsize=12, color='black')
    plt.ylim(0, 0.2)
    plt.legend()
    save_figure()
    sources = np.arange(-25, 26, step=5)
    audio_loc = np.array([0])
    Visual_stimuli_many = UniSensorySimulation1(sources, 2.5, 2000)
    Audio_stimuli_many = UniSensorySimulation1(audio_loc, 8, 2000)
    stimuli_means_nn1_unjumbled, stimuli_stds_nn1_unjumbled = evaluate_ann(Visual_stimuli_many, Audio_stimuli_many, sources, Neural_Net1_unjumbled)
    stimuli_means_nn1_jumbled, stimuli_stds_nn1_jumbled = evaluate_ann(Visual_stimuli_many, Audio_stimuli_many, sources, Neural_Net1_jumbled)
    stimuli_means_nn2_unjumbled, stimuli_stds_nn2_unjumbled = evaluate_ann(Visual_stimuli_many, Audio_stimuli_many, sources, Neural_Net2_unjumbled)
    stimuli_means_nn2_jumbled, stimuli_stds_nn2_jumbled = evaluate_ann(Visual_stimuli_many, Audio_stimuli_many, sources, Neural_Net2_jumbled)
    true_means, true_stds = mle_reference(Visual_stimuli_many, Audio_stimuli_many, sources)
    titles_means = ['NN1 Unjumbled Mean', 'NN1 Jumbled Mean', 'NN2 Unjumbled Mean', 'NN2 Jumbled Mean']
    titles_stds = ['NN1 Unjumbled Std', 'NN1 Jumbled Std', 'NN2 Unjumbled Std', 'NN2 Jumbled Std']
    means_data = [stimuli_means_nn1_unjumbled, stimuli_means_nn1_jumbled, stimuli_means_nn2_unjumbled, stimuli_means_nn2_jumbled]
    stds_data = [stimuli_stds_nn1_unjumbled, stimuli_stds_nn1_jumbled, stimuli_stds_nn2_unjumbled, stimuli_stds_nn2_jumbled]
    fig_means, axes_means = plt.subplots(1, 4, figsize=(20, 6), sharex=True)
    for j in range(4):
        ax = axes_means[j]
        ax.plot(sources, means_data[j], marker='o', linestyle='-', label=titles_means[j])
        ax.plot(sources, true_means, linestyle='-', label='Model')
        ax.set_title(titles_means[j])
        ax.set_xlabel('Spatial Disparity')
        ax.set_ylabel('Audiovisual Integration')
        ax.set_ylim(-1, 1)
        ax.legend()
        ax.grid()
    plt.tight_layout()
    save_figure()
    fig_stds, axes_stds = plt.subplots(1, 4, figsize=(20, 6), sharex=True)
    for j in range(4):
        ax = axes_stds[j]
        ax.plot(sources, stds_data[j], marker='o', linestyle='-', label=titles_stds[j])
        ax.plot(sources, true_stds, linestyle='-', label='Model')
        ax.set_title(titles_stds[j])
        ax.set_xlabel('Spatial Disparity')
        ax.set_ylabel('Standard Deviation')
        ax.set_ylim(0, 12)
        ax.legend()
        ax.grid()
    plt.tight_layout()
    save_figure()
    plt.rcParams.update({'font.size': 15})
    plt.figure(figsize=(10, 5))
    plt.plot(sources, stimuli_means_nn1_unjumbled, label='Neural Network', marker='o', linestyle='-')
    plt.plot(sources, true_means, label='Model', marker='x', linestyle='--', alpha=0.5)
    plt.xlabel('Spatial Disparity')
    plt.ylabel('Mean Bias')
    plt.title('Neural Network 1', loc='left')
    plt.legend()
    plt.ylim(0, 1)
    save_figure()
    plt.figure(figsize=(10, 5))
    plt.plot(sources, stimuli_stds_nn1_unjumbled, label='Neural Network', marker='o', linestyle='-')
    plt.plot(sources, true_stds, label='Model', marker='x', linestyle='--', alpha=0.5)
    plt.xlabel('Spatial Disparity')
    plt.ylabel('Standard Deviation')
    plt.title('Neural Network 1', loc='left')
    plt.legend()
    plt.ylim(0, 12)
    save_figure()
    plt.figure(figsize=(10, 5))
    plt.plot(sources, stimuli_means_nn2_unjumbled, label='Neural Network', marker='o', linestyle='-')
    plt.plot(sources, true_means, label='Model', marker='x', linestyle='--', alpha=0.5)
    plt.xlabel('Spatial Disparity')
    plt.ylabel('Mean Bias')
    plt.title('Neural Network 2', loc='left')
    plt.legend()
    plt.ylim(0, 1)
    save_figure()
    plt.figure(figsize=(10, 5))
    plt.plot(sources, stimuli_stds_nn2_unjumbled, label='Neural Network', marker='o', linestyle='-')
    plt.plot(sources, true_stds, label='Model', marker='x', linestyle='--', alpha=0.5)
    plt.xlabel('Spatial Disparity')
    plt.ylabel('Standard Deviation')
    plt.title('Neural Network 2', loc='left')
    plt.legend()
    plt.ylim(0, 12)
    save_figure()

if __name__ == "__main__":
    main()
